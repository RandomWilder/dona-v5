-- #278. A question from the portal is an ordinary ServiceCall on PORTAL.
-- The number is what the sender is shown the moment the question is received.

ALTER TABLE service_call DROP CONSTRAINT IF EXISTS service_call_source_channel_check;
ALTER TABLE service_call ADD CONSTRAINT service_call_source_channel_check CHECK (
  source_channel IN ('WHATSAPP', 'EMAIL', 'PHONE', 'WALK_IN', 'PORTAL')
);

ALTER TABLE conversation DROP CONSTRAINT IF EXISTS conversation_source_channel_check;
ALTER TABLE conversation ADD CONSTRAINT conversation_source_channel_check CHECK (
  source_channel IN ('WHATSAPP', 'EMAIL', 'PORTAL')
);

ALTER TABLE message DROP CONSTRAINT IF EXISTS message_source_channel_check;
ALTER TABLE message ADD CONSTRAINT message_source_channel_check CHECK (
  source_channel IN ('WHATSAPP', 'EMAIL', 'PORTAL')
);

ALTER TABLE service_call
  ADD COLUMN IF NOT EXISTS call_number integer GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE service_call DROP CONSTRAINT IF EXISTS service_call_call_number_key;
ALTER TABLE service_call
  ADD CONSTRAINT service_call_call_number_key UNIQUE (call_number);
