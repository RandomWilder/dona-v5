const WRAPPER =
  'viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"';

/** Inline SVG. No label means decorative. A label is what a screen reader hears. */
export function icon(
  name: IconName,
  options?: { class?: string; label?: string },
): Html {
  const drawing = drawings[name];
  const klass = options?.class;
  const label = options?.label;
  const classAttr =
    klass === undefined || klass === '' ? '' : ` class="${escapeHtml(klass)}"`;
  const access =
    label === undefined || label === ''
      ? ' aria-hidden="true"'
      : ` aria-label="${escapeHtml(label)}" role="img"`;
  return new Html(`<svg${classAttr} ${WRAPPER}${access}>${drawing}</svg>`);
}
