export const PORTAL_COPY: readonly PortalCopy[] = [...HEBREW, ...TRANSLATED];

const byKey = new Map(
  PORTAL_COPY.map((row) => [`${row.language}\n${row.key}`, row.text]),
);

const languageStore = new AsyncLocalStorage<string>();

/** Languages in the order their rows were written. A new language is rows, then it appears here. */
export function portalLanguages(): readonly string[] {
  const seen: string[] = [];
  for (const row of PORTAL_COPY) {
    if (!seen.includes(row.language)) seen.push(row.language);
  }
  return seen;
}

export function portalDir(language: string): 'rtl' | 'ltr' {
  return portalText('lang.dir', language) === 'rtl' ? 'rtl' : 'ltr';
}

/** The language of this request. Hebrew when nothing has chosen one. */
export function currentPortalLanguage(): string {
  return languageStore.getStore() ?? 'he';
}

export function bindPortalLanguage(language: string): void {
  languageStore.enterWith(language);
}

/** Keeps `language` for `body` and for every await inside it. */
export function runPortalLanguage<T>(language: string, body: () => T): T {
  return languageStore.run(language, body);
}

export function portalText(
  key: string,
  language: string = currentPortalLanguage(),
): string {
  const text = byKey.get(`${language}\n${key}`);
  if (text === undefined) {
    throw new Error(`missing portal copy: ${language}:${key}`);
  }
  return text;
}
